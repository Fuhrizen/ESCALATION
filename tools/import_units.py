#!/usr/bin/env python3
"""Extract explicitly mapped base naval ranges, never evaluate source modifiers.

Usage: python tools/import_units.py /path/to/Units --root .
Input directory contains Units.txt and Missile_defs.txt. Raw source stays local.
"""
import argparse
import hashlib
import json
import pathlib
import re

MAPPINGS = {'naval_gun': 'Ship Gun', 'anti_ship': 'Anti Ship Missile',
            'cruise': 'SSM', 'sub_torpedo': 'Torpedo',
            'depth_charge': 'DepthCharge'}


def clean(text):
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    return '\n'.join(re.split(r'//(?=(?:[^"\n]*"[^"\n]*")*[^"\n]*$)', line, maxsplit=1)[0]
                     for line in text.splitlines())


def extract(source):
    blocks = {}
    for match in re.finditer(r'^\s*\[MISSILE\]\s*"([^"]+)"(.*?)(?=^\s*\[MISSILE\]|\Z)',
                             clean(source), re.M | re.S):
        if match[1] in blocks:
            raise ValueError('Ambiguous duplicate missile: ' + match[1])
        blocks[match[1]] = match[2]
    result = []
    for native, name in MAPPINGS.items():
        body = blocks[name]
        # Anchored directives cannot mistake ImprovedBy/Set/case for base values.
        ranges = re.findall(r'^\s*Range\s+([\d.]+)\s*$', body, re.M)
        if len(ranges) != 1 or float(ranges[0]) <= 0:
            raise ValueError('Missing/ambiguous base Range: ' + name)
        item = {'nativeWeaponId': native, 'sourceMissile': name, 'rangeKm': float(ranges[0])}
        for field in ('Tech', 'Type', 'Icon'):
            m = re.search(r'^\s*' + field + r'\s+"([^"]+)"\s*$', body, re.M)
            if m:
                item[field.lower()] = m[1]
        item['unresolvedModifierLines'] = sum(bool(re.match(r'\s*(ImprovedBy|AffectedBy|DisablingTech)\b', line)) for line in body.splitlines())
        result.append(item)
    return result


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('source', type=pathlib.Path)
    ap.add_argument('--root', type=pathlib.Path, default=pathlib.Path('.'))
    args = ap.parse_args()
    files = {name: (args.source / name).read_bytes() for name in ('Units.txt', 'Missile_defs.txt', 'Missile_types.txt')}
    entries = extract(files['Missile_defs.txt'].decode('utf-8-sig'))
    manifest = {'schema': 1, 'source': 'User-supplied ICBM ESCALATION unit extracts; original rights retained',
                'sourceHashes': {name: hashlib.sha256(raw).hexdigest() for name, raw in files.items()},
                'policy': 'Base naval range directives only. No conditional tech, COPY/MODIFY, damage, time, speed, targets or asset binaries evaluated.',
                'weapons': entries}
    (args.root / 'data').mkdir(exist_ok=True)
    (args.root / 'data/source-weapons.json').write_text(json.dumps(manifest, indent=2) + '\n')
    lines = ['// Generated by tools/import_units.py; only unconditional source naval ranges.',
             'static double sourceWeaponRange(const std::string& id,double fallback){']
    for item in entries:
        lines.append('  if(id==%s)return %.8g;' % (json.dumps(item['nativeWeaponId']), item['rangeKm']))
    lines.extend(['  return fallback;', '}'])
    (args.root / 'src/source_weapon_ranges.inc').write_text('\n'.join(lines) + '\n')
    print('Imported %d proven base naval range bindings' % len(entries))


if __name__ == '__main__':
    main()
