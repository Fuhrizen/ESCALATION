#!/usr/bin/env python3
"""Import user-supplied ICBM extracts; preserve reference graph and supported mappings."""
import argparse, hashlib, json, pathlib, re
MAPPINGS={2:'Weapon_Modernization',8:'Improved_Army_Weapons',13:'Enhanced_Army_Weapons',3:'Improved_Basic_Protection',6:'Basic_Body_Armor',7:'Army_Mech_Mk2',19:'Improved_Body_Armor',26:'Advanced_Body_Armor',27:'Experimental_Body_Armor',32:'Portable_Electronic_Optics',33:'Tactical_Optics',35:'Advanced_Tactical_Optics',48:'Spec_Ops_Boost_1',49:'Spec_Ops_Boost_2',56:'Early_BM',58:'MRBM',59:'Nuclear_Fission',60:'ICBM',62:'Mobile_MRBM',63:'Improved_Inertial_Guidance',65:'Advanced_Inertial_Guidance',71:'Production_Booster_1',74:'Production_Booster_2',79:'Production_Booster_3',82:'Production_Booster_4',85:'Science_Booster_1',88:'Science_Booster_2',94:'Science_Booster_3',97:'Science_Booster_4',115:'Improved_Warships',117:'Missile_Warships',118:'Improved_Underwater_Weapons',119:'Cruise_Missile_Submarine',120:'Enhanced_Warships',121:'Improved_Submarines'}
def strip_comments(text):
    # Extract format has no multiline quoted values; preserve // inside quotes.
    text=re.sub(r'/\*.*?\*/','',text,flags=re.S)
    return '\n'.join(re.split(r'//(?=(?:[^"]*"[^"]*")*[^"]*$)',line,maxsplit=1)[0] for line in text.splitlines())
def parse(tech,levels):
    text=strip_comments(tech); records={}
    for m in re.finditer(r'\[([A-Z_]+)\]\s*"([^"]+)"(.*?)(?=\[[A-Z_]+\]|\Z)',text,re.S):
        if m[1]!='TECHNOLOGY':continue
        key=m[2]; b=m[3]; item={'key':key,'parents':[],'leadsTo':re.findall(r'\bLeadsTo\s+"([^"]+)"',b)}
        for name,out in [('Name','nameToken'),('Description','descriptionToken'),('Image','image'),('Type','category')]:
            match=re.search(r'\b'+name+r'\s+"([^"]+)"',b)
            if match:item[out]=match[1]
        for name,out in [('Points','points'),('TechLevel','level'),('NoAutoUnlockTillLevel','autoUnlockLevel')]:
            match=re.search(r'\b'+name+r'\s+([\d.]+)',b)
            if match:item[out]=float(match[1])
        if key in records:
            previous=records[key];previous['leadsTo']=list(dict.fromkeys(previous['leadsTo']+item['leadsTo']))
            previous.update({k:v for k,v in item.items() if k not in ('parents','leadsTo')});previous['duplicateDefinitions']=previous.get('duplicateDefinitions',1)+1
        else:records[key]=item
    for key,item in records.items():
        for child in item['leadsTo']:
            if child in records:records[child]['parents'].append(key)
    clean=strip_comments(levels)
    config={}
    for name in ['MinLevel','MaxLevel','NumLevels','NextLevelMultiplier','GeneralMultiplier']:
        m=re.search(r'\b'+name+r'\s+([\d.]+)',clean)
        if not m:raise ValueError('Missing '+name)
        config[name]=float(m[1])
    for key,mode,value in re.findall(r'\btech\s+"([^"]+)"\s+(Add|Cap)\s+([\d.]+)',clean):
        if key in records:records[key]['level'+mode]=float(value)
    for numeric,key in MAPPINGS.items():
        if key not in records or not records[key].get('points'):raise ValueError('Invalid supported mapping '+key)
        records[key]['nativeId']=numeric
    return {'schema':1,'source':'User-supplied Tech.txt and TechLevels.txt; original rights retained','sourceHashes':{'Tech.txt':hashlib.sha256(tech.encode()).hexdigest(),'TechLevels.txt':hashlib.sha256(levels.encode()).hexdigest()},'levelSettings':config,'technologies':list(records.values())}
def main():
    ap=argparse.ArgumentParser();ap.add_argument('tech');ap.add_argument('levels');ap.add_argument('--root',default='.');args=ap.parse_args()
    catalog=parse(pathlib.Path(args.tech).read_text(),pathlib.Path(args.levels).read_text());root=pathlib.Path(args.root)
    catalog['sourceHashes']={'Tech.txt':hashlib.sha256(pathlib.Path(args.tech).read_bytes()).hexdigest(),'TechLevels.txt':hashlib.sha256(pathlib.Path(args.levels).read_bytes()).hexdigest()}
    (root/'.test_tmp').mkdir(parents=True,exist_ok=True)
    (root/'.test_tmp/research-extracts.json').write_text(json.dumps(catalog,indent=2)+'\n')
    bykey={r['key']:r for r in catalog['technologies']};lines=['// Generated by tools/import_tech.py. Preserve numeric native IDs.']
    for ident,key in sorted(MAPPINGS.items()):
        r=bykey[key];values=[key,r.get('image',''),r.get('category','')]
        lines.append('mapExtract(%d,%s,%s,%s,%.8g,%.8g,%.8g);'%(ident,*[json.dumps(v) for v in values],r['level'],r['points'],r.get('levelAdd',0)))
    (root/'src/research_extracts.inc').write_text('\n'.join(lines)+'\n')
    print(f"Imported {len(bykey)} reference records, {len(MAPPINGS)} supported gameplay mappings")
if __name__=='__main__':main()
